function [tensor, Jac] = principal2tensor(lnkp1i,lnkp2i,lnkp3i,q1i,q2i,q3i,q4i)

lnkp1 = get_val(lnkp1i);
lnkp2 = get_val(lnkp2i);
lnkp3 = get_val(lnkp3i);
q1 = get_val(q1i);
q2 = get_val(q2i);
q3 = get_val(q3i);
q4 = get_val(q4i);

t2 = exp(lnkp1);
t3 = exp(lnkp2);
t4 = exp(lnkp3);
t5 = q1.^2;
t6 = q2.^2;
t7 = q3.^2;
t8 = q4.^2;
t9 = q1.*q2.*2.0;
t10 = q1.*q3.*2.0;
t11 = q1.*q4.*2.0;
t12 = q2.*q3.*2.0;
t13 = q2.*q4.*2.0;
t14 = q3.*q4.*2.0;
t15 = t5.*2.0;
t16 = t6.*2.0;
t17 = t7.*2.0;
t18 = t8.*2.0;
t19 = -t12;
t20 = -t13;
t21 = -t14;
t22 = t9+t14;
t23 = t10+t13;
t24 = t11+t12;
t25 = t9+t21;
t26 = t10+t20;
t27 = t11+t19;
t28 = t22.^2;
t29 = t23.^2;
t30 = t24.^2;
t34 = t15+t16-1.0;
t35 = t15+t17-1.0;
t36 = t15+t18-1.0;
t31 = t25.^2;
t32 = t26.^2;
t33 = t27.^2;
t37 = t2.*t30;
t38 = t3.*t28;
t39 = t4.*t29;
t46 = t34.^2;
t47 = t35.^2;
t48 = t36.^2;
t54 = q2.*t2.*t26.*4.0;
t56 = q3.*t3.*t27.*4.0;
t57 = q4.*t4.*t25.*4.0;
t76 = t2.*t24.*t26;
t77 = t3.*t22.*t27;
t78 = t4.*t23.*t25;
t82 = t2.*t24.*t34;
t83 = t3.*t22.*t35;
t84 = t4.*t23.*t36;
t85 = t2.*t26.*t34;
t86 = t3.*t27.*t35;
t87 = t4.*t25.*t36;
t49 = t2.*t32;
t50 = t3.*t33;
t51 = t4.*t31;
t61 = t2.*t46;
k11 = t39+t50+t61;
t62 = t3.*t47;
t63 = t4.*t48;
t79 = -t76;
t80 = -t77;
t81 = -t78;
t88 = -t85;
t89 = -t86;
k12 = t81+t82+t89;
k13 = t80+t84+t88;
k22 = t37+t51+t62;
t90 = -t87;
k23 = t79+t83+t90;
k33 = t38+t49+t63;

tensor = {k11, k12, k13, k22, k23, k33};

if nargout > 1
    t40 = q1.*t2.*t24.*4.0;
    t41 = q1.*t3.*t22.*4.0;
    t42 = q2.*t2.*t24.*4.0;
    t43 = q1.*t4.*t23.*4.0;
    t44 = q3.*t3.*t22.*4.0;
    t45 = q4.*t4.*t23.*4.0;
    t52 = q1.*t2.*t26.*4.0;
    t53 = q1.*t3.*t27.*4.0;
    t55 = q1.*t4.*t25.*4.0;
    t64 = q1.*t2.*t34.*2.0;
    t65 = q2.*t2.*t34.*2.0;
    t66 = q1.*t3.*t35.*2.0;
    t67 = q3.*t2.*t34.*2.0;
    t68 = q2.*t3.*t35.*2.0;
    t69 = q4.*t2.*t34.*2.0;
    t70 = q1.*t4.*t36.*2.0;
    t71 = q3.*t3.*t35.*2.0;
    t72 = q2.*t4.*t36.*2.0;
    t73 = q4.*t3.*t35.*2.0;
    t74 = q3.*t4.*t36.*2.0;
    t75 = q4.*t4.*t36.*2.0;
    t58 = -t54;
    t59 = -t56;
    t60 = -t57;
    
    Jac = zeros(numel(k11)*6,0);
    Jac = combineJacobians(Jac, lnkp1i, @get_jac_lnkp1);
    Jac = combineJacobians(Jac, lnkp2i, @get_jac_lnkp2);
    Jac = combineJacobians(Jac, lnkp3i, @get_jac_lnkp3);
    Jac = combineJacobians(Jac, q1i, @get_jac_q1);
    Jac = combineJacobians(Jac, q2i, @get_jac_q2);
    Jac = combineJacobians(Jac, q3i, @get_jac_q3);
    Jac = combineJacobians(Jac, q4i, @get_jac_q4);
end
function jac_lnkp1 = get_jac_lnkp1()
    dk11_dlnkp1 = addGradient([], lnkp1i, @() t61);
    dk12_dlnkp1 = addGradient([], lnkp1i, @() t82);
    dk13_dlnkp1 = addGradient([], lnkp1i, @() t88);
    dk22_dlnkp1 = addGradient([], lnkp1i, @() t37);
    dk23_dlnkp1 = addGradient([], lnkp1i, @() t79);
    dk33_dlnkp1 = addGradient([], lnkp1i, @() t49);
    jac_lnkp1 = [dk11_dlnkp1; dk12_dlnkp1; dk13_dlnkp1; dk22_dlnkp1; dk23_dlnkp1; dk33_dlnkp1];
end
function jac_lnkp2 = get_jac_lnkp2()
    dk11_dlnkp2 = addGradient([], lnkp2i, @() t50);
    dk12_dlnkp2 = addGradient([], lnkp2i, @() t89);
    dk13_dlnkp2 = addGradient([], lnkp2i, @() t80);
    dk22_dlnkp2 = addGradient([], lnkp2i, @() t62);
    dk23_dlnkp2 = addGradient([], lnkp2i, @() t83);
    dk33_dlnkp2 = addGradient([], lnkp2i, @() t38);
    jac_lnkp2 = [dk11_dlnkp2; dk12_dlnkp2; dk13_dlnkp2; dk22_dlnkp2; dk23_dlnkp2; dk33_dlnkp2];
end
function jac_lnkp3 = get_jac_lnkp3()
    dk11_dlnkp3 = addGradient([], lnkp3i, @() t39);
    dk12_dlnkp3 = addGradient([], lnkp3i, @() t81);
    dk13_dlnkp3 = addGradient([], lnkp3i, @() t84);
    dk22_dlnkp3 = addGradient([], lnkp3i, @() t51);
    dk23_dlnkp3 = addGradient([], lnkp3i, @() t90);
    dk33_dlnkp3 = addGradient([], lnkp3i, @() t63);
    jac_lnkp3 = [dk11_dlnkp3; dk12_dlnkp3; dk13_dlnkp3; dk22_dlnkp3; dk23_dlnkp3; dk33_dlnkp3];
end
function jac_q1 = get_jac_q1()
    dk11_dq1 = addGradient([], q1i, @() q3.*t4.*t23.*4.0+q4.*t3.*t27.*4.0+q1.*t2.*t34.*8.0);
    dk12_dq1 = addGradient([], q1i, @() t40-t53+t69-t73-q2.*t4.*t23.*2.0-q3.*t4.*t25.*2.0);
    dk13_dq1 = addGradient([], q1i, @() t43-t52-t67+t74-q4.*t3.*t22.*2.0-q2.*t3.*t27.*2.0);
    dk22_dq1 = addGradient([], q1i, @() q4.*t2.*t24.*4.0+q2.*t4.*t25.*4.0+q1.*t3.*t35.*8.0);
    dk23_dq1 = addGradient([], q1i, @() t41-t55+t68-t72-q3.*t2.*t24.*2.0-q4.*t2.*t26.*2.0);
    dk33_dq1 = addGradient([], q1i, @() q2.*t3.*t22.*4.0+q3.*t2.*t26.*4.0+q1.*t4.*t36.*8.0);
    jac_q1 = [dk11_dq1; dk12_dq1; dk13_dq1; dk22_dq1; dk23_dq1; dk33_dq1];
end
function jac_q2 = get_jac_q2()
    dk11_dq2 = addGradient([], q2i, @() t45+t59+q2.*t2.*t34.*8.0);
    dk12_dq2 = addGradient([], q2i, @() t42+t67+t71-q1.*t4.*t23.*2.0-q4.*t4.*t25.*2.0);
    dk13_dq2 = addGradient([], q2i, @() t58+t69+t75+q3.*t3.*t22.*2.0-q1.*t3.*t27.*2.0);
    dk22_dq2 = addGradient([], q2i, @() t55+q3.*t2.*t24.*4.0);
    dk23_dq2 = addGradient([], q2i, @() t66-t70+q4.*t2.*t24.*2.0-q3.*t2.*t26.*2.0);
    dk33_dq2 = addGradient([], q2i, @() t41-q4.*t2.*t26.*4.0);
    jac_q2 = [dk11_dq2; dk12_dq2; dk13_dq2; dk22_dq2; dk23_dq2; dk33_dq2];
end
function jac_q3 = get_jac_q3()
    dk11_dq3 = addGradient([], q3i, @() t43-q2.*t3.*t27.*4.0);
    dk12_dq3 = addGradient([], q3i, @() t59+t65+t68-q1.*t4.*t25.*2.0+q4.*t4.*t23.*2.0);
    dk13_dq3 = addGradient([], q3i, @() -t64+t70+q2.*t3.*t22.*2.0-q4.*t3.*t27.*2.0);
    dk22_dq3 = addGradient([], q3i, @() t42+t60+q3.*t3.*t35.*8.0);
    dk23_dq3 = addGradient([], q3i, @() t44+t73+t75-q1.*t2.*t24.*2.0-q2.*t2.*t26.*2.0);
    dk33_dq3 = addGradient([], q3i, @() t52+q4.*t3.*t22.*4.0);
    jac_q3 = [dk11_dq3; dk12_dq3; dk13_dq3; dk22_dq3; dk23_dq3; dk33_dq3];
end
function jac_q4 = get_jac_q4()
    dk11_dq4 = addGradient([], q4i, @() t53+q2.*t4.*t23.*4.0);
    dk12_dq4 = addGradient([], q4i, @() t64-t66+q3.*t4.*t23.*2.0-q2.*t4.*t25.*2.0);
    dk13_dq4 = addGradient([], q4i, @() t45+t65+t72-q1.*t3.*t22.*2.0-q3.*t3.*t27.*2.0);
    dk22_dq4 = addGradient([], q4i, @() t40-q3.*t4.*t25.*4.0);
    dk23_dq4 = addGradient([], q4i, @() t60+t71+t74+q2.*t2.*t24.*2.0-q1.*t2.*t26.*2.0);
    dk33_dq4 = addGradient([], q4i, @() t44+t58+q4.*t4.*t36.*8.0);
    jac_q4 = [dk11_dq4; dk12_dq4; dk13_dq4; dk22_dq4; dk23_dq4; dk33_dq4];
end
end