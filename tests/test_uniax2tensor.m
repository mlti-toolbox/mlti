function [out, Jac] = obj_fun(lnkperp,lnkpar,v1,v2,v3)
    if nargout < 2
        tensor = uniax2tensor(lnkperp,lnkpar,v1,v2,v3);
    else
        [tensor, Jac] = uniax2tensor(lnkperp,lnkpar,v1,v2,v3);
    end
    out = horzcat(tensor{:});
    out = out(:);
end