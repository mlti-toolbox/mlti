end

function test_checkGradients_all_design_variables(testCase)
    [N,n] = size(testCase.TestData.k11);
    x0 = [
        testCase.TestData.k11(:).',...
        testCase.TestData.k12(:).',...
        testCase.TestData.k13(:).',...
        testCase.TestData.k22(:).',...
        testCase.TestData.k23(:).',...
        testCase.TestData.k33(:).'...
    ];
    if ~checkGradients(@(x) obj_fun( ...
            DesignVariable(reshape(x(0*n*N+1:1*n*N),N,n),reshape((0*n*N+1:1*n*N),N,n),length(x0)),...
            DesignVariable(reshape(x(1*n*N+1:2*n*N),N,n),reshape((1*n*N+1:2*n*N),N,n),length(x0)),...
            DesignVariable(reshape(x(2*n*N+1:3*n*N),N,n),reshape((2*n*N+1:3*n*N),N,n),length(x0)),...
            DesignVariable(reshape(x(3*n*N+1:4*n*N),N,n),reshape((3*n*N+1:4*n*N),N,n),length(x0)),...
            DesignVariable(reshape(x(4*n*N+1:5*n*N),N,n),reshape((4*n*N+1:5*n*N),N,n),length(x0)),...
            DesignVariable(reshape(x(5*n*N+1:6*n*N),N,n),reshape((5*n*N+1:6*n*N),N,n),length(x0))...
        ), x0, testCase.TestData.options, Display="on")
        error("checkGradients Failed!")
    end
end

