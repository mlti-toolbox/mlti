function setupOnce(testCase)
    N = randi([4,7]);
    n = randi([5,8]);
    testCase.TestData.k11 = unifrnd(0.1,500,N,n);
    testCase.TestData.k12 = unifrnd(0.1,500,N,n);
    testCase.TestData.k13 = unifrnd(0.1,500,N,n);
    testCase.TestData.k22 = unifrnd(0.1,500,N,n);
    testCase.TestData.k23 = unifrnd(0.1,500,N,n);
    testCase.TestData.k33 = unifrnd(0.1,500,N,n);
    testCase.TestData.options = optimoptions("fminunc", FiniteDifferenceType="central");

    timestamp = string(datetime("now", Format="uuuu-MM-dd_HH-mm-ss.SSS"));
    testCase.onFailure(@() logFailure(testCase, timestamp));
end

