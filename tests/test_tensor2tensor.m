        error("checkGradients Failed!")
    end
end

function [out, Jac] = obj_fun(k11, k12, k13, k22, k23, k33)
    if nargout < 2
        tensor = tensor2tensor(k11, k12, k13, k22, k23, k33);
    else
        [tensor, Jac] = tensor2tensor(k11, k12, k13, k22, k23, k33);
    end
    out = horzcat(tensor{:});
    out = out(:);
end