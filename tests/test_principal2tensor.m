function [out, Jac] = obj_fun(lnkp1,lnkp2,lnkp3,q1,q2,q3,q4)
    if nargout < 2
        tensor = principal2tensor(lnkp1,lnkp2,lnkp3,q1,q2,q3,q4);
    else
        [tensor, Jac] = principal2tensor(lnkp1,lnkp2,lnkp3,q1,q2,q3,q4);
    end
    out = horzcat(tensor{:});
    out = out(:);
end